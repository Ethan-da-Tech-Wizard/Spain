// Fit in the mod: SpainMod is the entry point Fabric calls on both client and dedicated server (declared
// as "main" in src/main/resources/fabric.mod.json). It creates the two shared services, FlightSystem (rocket
// building, flight, space/planet transitions; FLIGHT) and SporeVisuals (player appearance; VISUALS), hooks them
// to server events, and defines the /spain chat commands that call into them. All game logic lives in
// those two classes; this file is only wiring.
// //
// The data pack (generated by tools/build_pack.py and extend_pack.py) and this mod cooperate through
// scoreboard triggers and entity tags: the pack sets tags such as spain.request.board on a player, and
// FlightSystem.tick consumes them. Commands below offer the same actions to players who type them.
// //
// Limits: state is kept in memory and saved on SERVER_STOPPING (and on demand); a server crash loses
// changes since the last save. No operator permission is required for the /spain commands.
package dev.spain;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.command.v2.CommandRegistrationCallback;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.minecraft.commands.Commands;

import net.minecraft.commands.arguments.coordinates.BlockPosArgument;

/** Server-side entry point; Fabric instantiates it once and calls {@link #onInitialize()}. */
public final class SpainMod implements ModInitializer {
    // Single shared instances (static so the command lambdas, event handlers and the verification probe in
    // verification/MinecraftChecks.java can all reach them). They hold per-player data keyed by UUID.
    public static final FlightSystem FLIGHT = new FlightSystem();
    public static final SporeVisuals VISUALS = new SporeVisuals();

    // Runs once at startup, before any world loads: registers network payloads, event handlers and commands.
    @Override public void onInitialize() {
        // Declare the FlightView packet (server to client) so both sides agree on its id and binary layout. SpainClient registers the receiving end.
        net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry.clientboundPlay().register(FlightView.TYPE,FlightView.CODEC);

        // Give FlightSystem a way to send the camera packet without depending on networking classes. canSend() is false for
        // players whose game has no Spain mod (vanilla clients can join and simply miss the chase camera).
        FLIGHT.view=(player,payload)->{
            if(net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking.canSend(player,FlightView.TYPE))
                net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking.send(player,payload);
        };

        // Load saved ships and avatars once the server (and its worlds) exist.
        ServerLifecycleEvents.SERVER_STARTED.register(FLIGHT::load);
        ServerLifecycleEvents.SERVER_STARTED.register(VISUALS::load);

        // Run both systems after vanilla finishes each tick (20 times a second), so they see the final player positions of that tick.
        ServerTickEvents.END_SERVER_TICK.register(FLIGHT::tick);
        ServerTickEvents.END_SERVER_TICK.register(VISUALS::tick);

        // Persist on shutdown; VISUALS.clear() also removes the temporary display entities so none are left in the world.
        ServerLifecycleEvents.SERVER_STOPPING.register(FLIGHT::save);
        ServerLifecycleEvents.SERVER_STOPPING.register(server -> { VISUALS.save(server); VISUALS.clear(); });

        // Build the /spain command tree. Each sub-command maps to a FlightSystem or SporeVisuals method; the
        // lambdas return Minecraft's success value (1) or the method's own result. getPlayerOrException() makes
        // a command run from the console fail cleanly instead of crashing.
        CommandRegistrationCallback.EVENT.register((dispatcher, context, selection) -> {
            // /spain create | design <part> | avatar <mode|capture> | capture | board | land | help | spore | recall | corner1/corner2 <x y z>.
            var command=Commands.literal("spain");
            command.then(Commands.literal("create").executes(c->{FLIGHT.action(c.getSource().getPlayerOrException(),"create");return 1;}));

            // /spain design <hull|wings|engine|cabin|stretch|rotate|undo|clear>: the same parts the rocket creator dialog (extend_pack.py) offers.
            var design=Commands.literal("design");
            for(String part:new String[]{"hull","wings","engine","cabin","stretch","rotate","undo","clear"})
                design.then(Commands.literal(part).executes(c->FLIGHT.design(c.getSource().getPlayerOrException(),part)));
            command.then(design);

            // /spain avatar default|spore|custom switches how the player looks; /spain avatar capture saves their current build as the custom creature.
            var avatar=Commands.literal("avatar");
            for(String mode:new String[]{"default","spore","custom"})
                avatar.then(Commands.literal(mode).executes(c -> {VISUALS.select(c.getSource().getPlayerOrException(),mode);return 1;}));
            avatar.then(Commands.literal("capture").executes(c -> FLIGHT.captureAvatar(c.getSource().getPlayerOrException())));
            command.then(avatar);
            for (String name : new String[]{"capture","board","land","help","spore","recall"})
                command.then(Commands.literal(name).executes(c -> FLIGHT.action(c.getSource().getPlayerOrException(),name)));

            // /spain corner1 and corner2 <position>: select two opposite corners of a larger blueprint to capture (the dialog text calls this "no part-count limit"). `corner` is a final copy because lambdas can only capture final variables.
            for (int n=1;n<=2;n++) {
                final int corner=n;
                command.then(Commands.literal("corner"+n).then(Commands.argument("position",BlockPosArgument.blockPos()).executes(c -> {
                    FLIGHT.corner(c.getSource().getPlayerOrException(),corner,BlockPosArgument.getBlockPos(c,"position")); return 1;
                })));
            }

            // Registering the root node makes the whole tree available in game.
            dispatcher.register(command);
        });
        org.slf4j.LoggerFactory.getLogger("Spain").info("Spain flight system ready: /spain help");
    }
}
